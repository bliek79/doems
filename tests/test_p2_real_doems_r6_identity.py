"""Use the real R6 proposal builder, not hand-authored scheduler proposals.

This proves the genuine DOEMS output shape and explicitly proves that a
separate Alpha84 planner does NOT automatically recognize DOEMS identities.
It does not claim a live two-integration acceptance test.
"""
from datetime import datetime, timedelta, timezone
import pytest
from custom_components.doems.automatic_slot_bridge_model import build_automatic_slot_proposals
from custom_components.doems.alpha84_handoff_contract import project_combined_slot
from custom_components.doems.alpha84_plan_lineage import audit_plan_lineage
from custom_components.doems.alpha84_handoff_contract import HandoffContractError


def actual_doems_proposal():
    start = datetime(2026, 10, 27, 12, tzinfo=timezone.utc)
    rows = []
    for index in range(288):
        st = start + index * timedelta(minutes=15)
        rows.append({
            "index": index, "start": st.isoformat(),
            "end": (st + timedelta(minutes=15)).isoformat(),
            "start_soc_percent": 40.0,
            "charge_from_grid_trade_kwh": 0.125 if index == 2 else 0.0,
            "price_source": "known",
        })
    snapshot = {
        "status": "ready", "valid": True,
        "native_slot_count": 288, "native_slots": rows,
        "capacity_kwh": 7.1, "charge_efficiency_percent": 95,
        "discharge_efficiency_percent": 95,
        "max_charge_power_w": 800, "max_discharge_power_w": 800,
    }
    result = build_automatic_slot_proposals(
        snapshot, now=start - timedelta(minutes=15)
    )
    assert result["valid"], result
    assert len(result["proposals"]) == 1, result
    return result["proposals"][0]


def test_real_doems_r6_proposal_projects_with_unchanged_origin_and_identity():
    proposal = actual_doems_proposal()
    assert proposal["origin"] == "automatic_72h_planner"
    assert proposal["planner_identity"]
    assert proposal["planner_signature"]
    slot = {**proposal, "lifecycle_status": "pending"}
    selection = {
        "selected_slot": 1, "selected_lifecycle": "pending",
        "selected_action": proposal["action"],
        "safety_status": "safe", "safety_blockers": [],
    }
    projected = project_combined_slot(
        selection, slot, sources_fresh=True, safety_safe=True
    )
    detail = projected["scheduler_slots"][1]
    assert detail["planner_identity"] == proposal["planner_identity"]
    assert detail["planner_signature"] == proposal["planner_signature"]
    assert detail["origin"] == "automatic_72h_planner"
    assert projected["physical_execution_enabled"] is False


def test_independent_original_planner_does_not_automatically_recognize_real_doems_plan():
    proposal = actual_doems_proposal()
    slot = {**proposal, "lifecycle_status": "pending"}
    selection = {
        "selected_slot": 1, "selected_lifecycle": "pending",
        "selected_action": proposal["action"],
        "safety_status": "safe", "safety_blockers": [],
    }
    projected = project_combined_slot(selection, slot, sources_fresh=True, safety_safe=True)
    # A loaded original Alpha84 planner provides its own candidates, not
    # automatically those just generated by DOEMS R6.
    with pytest.raises(HandoffContractError, match="authoritative original candidate"):
        audit_plan_lineage(slot, projected, {
            "auto_bridge_candidates": [], "auto_bridge_slot_preview": []
        })
